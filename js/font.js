const GLYPHS = {};
for (const ch in FONT) GLYPHS[ch] = FONT[ch].split('|');

const _textCache = new Map();

function textWidth(str, scale = 1) {
  str = String(str);
  return str.length ? (str.length * 6 - 1) * scale : 0;
}

// color: string, atau array 7 warna (gradasi per baris)
function _buildText(str, color, outline) {
  const pad = outline ? 1 : 0;
  const w = Math.max(1, textWidth(str) + pad * 2), h = 7 + pad * 2;
  const c = makeCanvas(w, h);
  const g = c.getContext('2d');
  const pts = [];
  for (let i = 0; i < str.length; i++) {
    const gl = GLYPHS[str[i]] || GLYPHS[' '];
    for (let y = 0; y < 7; y++) {
      const row = gl[y];
      for (let x = 0; x < 5; x++) if (row[x] === '#') pts.push(i * 6 + x + pad, y + pad, y);
    }
  }
  if (outline) {
    g.fillStyle = outline;
    for (let i = 0; i < pts.length; i += 3) g.fillRect(pts[i] - 1, pts[i + 1] - 1, 3, 3);
  }
  for (let i = 0; i < pts.length; i += 3) {
    g.fillStyle = Array.isArray(color) ? color[pts[i + 2]] : color;
    g.fillRect(pts[i], pts[i + 1], 1, 1);
  }
  return c;
}

function drawText(ctx, str, x, y, opts = {}) {
  str = String(str).toUpperCase();
  const color = opts.color || '#ffffff';
  const scale = opts.scale || 1;
  const outline = opts.outline || null;
  const key = str + '\u0001' + (Array.isArray(color) ? color.join(',') : color) + '\u0001' + outline;
  let c = _textCache.get(key);
  if (!c) {
    if (_textCache.size > 600) _textCache.clear();
    c = _buildText(str, color, outline);
    _textCache.set(key, c);
  }
  const w = c.width * scale;
  let dx = x;
  if (opts.align === 'center') dx = x - w / 2;
  else if (opts.align === 'right') dx = x - w;
  const pad = outline ? scale : 0;
  ctx.drawImage(c, Math.round(dx), Math.round(y - pad), w, c.height * scale);
  return w;
}
